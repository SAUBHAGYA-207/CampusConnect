const express = require('express');
const router = express.Router();
const serviceController = require('../controllers/serviceController');
const { requireAuth, requireRole } = require('../middleware/auth');
const upload = require('../middleware/upload');

// Protect all provider routes
router.use(requireAuth, requireRole('provider'));

router.get('/dashboard', (req, res) => res.redirect('/dashboard'));
router.get('/my-services', serviceController.getMyServices);

router.get('/create', serviceController.getCreateService);
router.post('/create', upload.single('image'), serviceController.postCreateService);

router.get('/:id/edit', serviceController.getEditService);
router.post('/:id/edit', upload.single('image'), serviceController.postEditService);

router.post('/:id/delete', serviceController.deleteService);

// Partner Payout & UPI Registration (Auto QR Generated by System)
const { partnerQrUpload } = require('../middleware/upload');
router.post('/payout-qr', (req, res, next) => {
    if (req.is('multipart/form-data')) {
        partnerQrUpload.single('partnerQrImage')(req, res, next);
    } else {
        next();
    }
}, serviceController.postPayoutQr);
router.post('/request-payout', serviceController.postRequestPayout);

module.exports = router;
